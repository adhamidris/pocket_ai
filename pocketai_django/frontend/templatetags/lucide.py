def _render_element(tag: str, attrs: dict[str, str]) -> str:
    attr_html = " ".join(f'{key}="{value}"' for key, value in attrs.items())
    return f"<{tag} {attr_html} />"


@register.simple_tag
def lucide(icon: str, classes: str = "h-5 w-5", stroke_width: str = "2") -> str:
    paths = ICON_PATHS.get(icon)
    if not paths:
        return ""
    children = "".join(_render_element(tag, attrs) for tag, attrs in paths)
    class_attr = f' class="{classes}"' if classes else ""
    svg = (
        f"<svg{class_attr} xmlns=\"http://www.w3.org/2000/svg\" "
        f"viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" "
        f"stroke-width=\"{stroke_width}\" stroke-linecap=\"round\" stroke-linejoin=\"round\">"
        f"{children}</svg>"
    )
    return mark_safe(svg)
